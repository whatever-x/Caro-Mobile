package com.whatever.caro.core.ui.swipe

/**
 * 스와이프 제스처가 완료될 수 있는 방향을 나타냅니다.
 *
 * @author gunhyung
 */
enum class SwipeDirection {
    /**
     * composable을 왼쪽으로 스와이프하는 방향입니다.
     */
    LEFT,

    /**
     * composable을 오른쪽으로 스와이프하는 방향입니다.
     */
    RIGHT,

    /**
     * composable을 위쪽으로 스와이프하는 방향입니다.
     */
    UP,
}
